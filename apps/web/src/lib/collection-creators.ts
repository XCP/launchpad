/**
 * Who created the cards in seven Counterparty collections, keyed by the
 * explorer's collection tag. Shipped as data rather than looked up: no
 * request, no per-row lookup, badges the moment the list renders.
 *
 * It is a separate chunk. About 1,200 distinct addresses is ~32 KB gzipped
 * however it is encoded (base58 does not compress), so address-badges.tsx
 * loads this lazily, after the list is on screen, and the browser caches
 * the hashed chunk from then on. Nothing here is on the critical path.
 *
 * Derived 2026-09-06 from the xcp.io explorer index. "Creator" is the source
 * of each asset's first valid issuance; for every series here that is also
 * the current issuer of every card (Kaleidoscope: one card transferred), so
 * ownership transfers have not moved a badge. Rare Pepe and Bitcorn are
 * closed series and never change; the other five still issue, so their
 * lists go stale until regenerated. To regenerate, run against the
 * explorer's core D1 per tag:
 *
 *   WITH m AS (
 *     SELECT a.asset_id FROM tags t
 *     JOIN entity_dictionary e ON e.entity_id=t.entity_id AND e.entity_type='asset'
 *     JOIN asset_dictionary d ON d.asset=e.entity_key
 *     JOIN assets a ON a.asset_id=d.asset_id
 *     WHERE t.tag=?                      -- 'rare-pepe', 'bitcorn', ...
 *   ), first AS (
 *     SELECT i.asset_id, i.source_id FROM issuances i JOIN m ON m.asset_id=i.asset_id
 *     WHERE i.event_index=(SELECT min(event_index) FROM issuances x
 *                          WHERE x.asset_id=i.asset_id AND x.status='valid')
 *   )
 *   SELECT DISTINCT ad.address FROM first
 *   JOIN address_dictionary ad ON ad.address_id=first.source_id ORDER BY 1;
 */

